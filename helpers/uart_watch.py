#!/usr/bin/env python3
"""
GENERATED BY CLAUDE!!!
Live UART dashboard for an fx2lafw logic analyzer.

Streams UART bytes (decoded by sigrok) from an fx2lafw device, frames them into
packets -- either by a start code (default 0xFFAA) or by a fixed byte length --
and shows the current packet as a fixed, self-refreshing dashboard: a byte-index
row above the hex values, wrapped every N bytes, with any byte that changes
staying highlighted for several seconds. Chosen bytes can be broken out into
individual bits, and chosen bytes can be flagged and their changes logged.

Requires: sigrok-cli  (https://sigrok.org)  with fx2lafw firmware present.

Examples:
    python uart_watch.py --channel D1
    python uart_watch.py --length 16 --offset 0          # fixed-length framing
    python uart_watch.py --columns 8 --breakout 4,7
    python uart_watch.py --watch 4,8 --log changes.log   # flag + log changes
    python uart_watch.py --demo --length 9 --watch 8 --log demo.log

fx2lafw names its 8 channels D0..D7. Pass whichever the UART line is wired to
(their "channel 1" is usually D1, but check your board's labels).
"""

import argparse
import re
import shutil
import subprocess
import sys
import time
from datetime import datetime

# ---- ANSI styling -----------------------------------------------------------
RESET        = "\033[0m"
DIM          = "\033[2m"
UNDERLINE    = "\033[4m"
HEADER_COL   = "\033[36m"       # cyan: the packet header bytes
CHANGED      = "\033[30;103m"   # black on bright-yellow: just changed
CHANGED_FADE = "\033[30;43m"    # black on dim-yellow: changed a moment ago
CLEAR_HOME   = "\033[2J\033[H"
CURSOR_HOME  = "\033[H"
CLEAR_BELOW  = "\033[J"
HIDE_CURSOR  = "\033[?25l"
SHOW_CURSOR  = "\033[?25h"

PAINT_INTERVAL = 0.1            # seconds; caps redraw rate when idle


def parse_int_list(s):
    out = []
    for tok in s.split(","):
        tok = tok.strip()
        if not tok:
            continue
        try:
            v = int(tok)
        except ValueError:
            continue
        if v >= 0:
            out.append(v)
    return sorted(set(out))


def parse_args():
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--channel", default="D1",
                   help="LA channel the UART line is on (fx2lafw = D0..D7). "
                        "Default: D1")
    p.add_argument("--baudrate", type=int, default=115200,
                   help="UART baud rate. Default: 115200")
    p.add_argument("--samplerate", default="4m",
                   help="Capture sample rate, e.g. 1m, 4m, 8m, 24m. "
                        "Higher = more reliable decode. Default: 4m")
    p.add_argument("--device", default="fx2lafw",
                   help="sigrok device driver. Default: fx2lafw")

    # --- framing: start-code (default) OR fixed length ---
    p.add_argument("--header", default="55AA",
                   help="Start-code framing: packet start marker, hex. "
                        "Default: 55AA")
    p.add_argument("--length", type=int, default=0, metavar="N",
                   help="Fixed-length framing: split the stream into N-byte "
                        "packets instead of using --header. Default: off")
    p.add_argument("--offset", type=int, default=0, metavar="K",
                   help="Fixed-length framing only: skip K bytes before "
                        "framing starts, to align the phase. Default: 0")

    p.add_argument("--columns", type=int, default=8,
                   help="Bytes per row before wrapping. Default: 8")
    p.add_argument("--breakout", default="", metavar="BYTES",
                   help="Comma-separated byte positions to expand into "
                        "individual bits, e.g. 4,7")
    p.add_argument("--watch", default="", metavar="BYTES",
                   help="Comma-separated byte positions to flag and log on "
                        "change, e.g. 4,8")
    p.add_argument("--log", default="", metavar="FILE",
                   help="File to append watched-byte changes to. Defaults to "
                        "'uart_changes.log' when --watch is set.")
    p.add_argument("--highlight-seconds", type=float, default=3.0,
                   help="How long a byte/bit stays highlighted after it "
                        "changes. Default: 3.0")
    p.add_argument("--no-color", action="store_true",
                   help="Disable ANSI colors (uses a '^' marker row instead).")
    p.add_argument("--demo", action="store_true",
                   help="Generate synthetic packets instead of using hardware.")
    return p.parse_args()


# ---- sigrok plumbing --------------------------------------------------------
def build_command(args):
    decoder = (f"uart:rx={args.channel}"
               f":baudrate={args.baudrate}:format=hex")
    return [
        "sigrok-cli",
        "--driver", args.device,
        "--continuous",
        "--config", f"samplerate={args.samplerate}",
        "--channels", args.channel,
        "--protocol-decoders", decoder,
        "--protocol-decoder-annotations", "uart=rx-data",
    ]


_BYTE_RE = re.compile(r"(?:0x)?([0-9A-Fa-f]{1,2})")


def iter_bytes_from_sigrok(proc):
    """Yield integer byte values from sigrok-cli annotation output.

    Lines look like:  'uart-1: FF'  or  'uart-1: 0xFF'
    """
    for line in proc.stdout:
        line = line.strip()
        if not line:
            continue
        payload = line.split(":", 1)[1].strip() if ":" in line else line
        m = _BYTE_RE.fullmatch(payload) or _BYTE_RE.search(payload)
        if not m:
            continue
        try:
            yield int(m.group(1), 16)
        except ValueError:
            continue


# ---- packet framing ---------------------------------------------------------
def packetize_header(byte_iter, header_bytes):
    """Frame by start code. Each yielded packet is the previous complete one
    (header included); bytes before the first header are discarded."""
    header = list(header_bytes)
    hlen = len(header)
    current = []
    seen_header = False
    for b in byte_iter:
        current.append(b)
        if current[-hlen:] == header:
            prefix = current[:-hlen]
            if seen_header and prefix:
                yield prefix
            seen_header = True
            current = list(header)


def packetize_fixed(byte_iter, length, offset=0):
    """Frame by fixed length. Skip `offset` bytes to align, then yield every
    `length` bytes as a packet (emitted as soon as it is full)."""
    skipped = 0
    buf = []
    for b in byte_iter:
        if skipped < offset:
            skipped += 1
            continue
        buf.append(b)
        if len(buf) == length:
            yield buf
            buf = []


# ---- rendering --------------------------------------------------------------
def _style(age, hl, i, hlen):
    """Return the ANSI style prefix (no reset) for a value cell."""
    if i < hlen:
        return HEADER_COL
    if age < hl * 0.5:
        return CHANGED
    if age < hl:
        return CHANGED_FADE
    return ""


def render_grid(values, changed_at, hlen, now, hl, use_color, columns,
                watch_set=frozenset()):
    """Byte grid wrapped every `columns` bytes, index row above each block.
    Watched bytes are underlined (color) so they stand out."""
    n = len(values)
    col_w = max(2, len(str(n - 1))) if n else 2
    lines = []
    for start in range(0, n, columns):
        idx_cells, val_cells, mark_cells = [], [], []
        for i in range(start, min(start + columns, n)):
            lab = str(i).rjust(col_w)
            val = f"{values[i]:02X}".rjust(col_w)
            age = now - changed_at[i]
            if use_color:
                if i in watch_set:
                    idx_cells.append(f"{UNDERLINE}{DIM}{lab}{RESET}")
                else:
                    idx_cells.append(f"{DIM}{lab}{RESET}")
                prefix = _style(age, hl, i, hlen)
                if i in watch_set:
                    prefix = UNDERLINE + prefix
                val_cells.append(f"{prefix}{val}{RESET}" if prefix else val)
            else:
                idx_cells.append(lab)
                val_cells.append(val)
                mark = ("^" * len(val.strip())).rjust(col_w) if age < hl \
                    else " " * col_w
                mark_cells.append(mark)
        lines.append(" ".join(idx_cells))
        lines.append(" ".join(val_cells))
        if not use_color:
            lines.append(" ".join(mark_cells))
        lines.append("")
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def render_breakouts(values, bit_changed_at, breakout, now, hl, use_color):
    """Expand chosen byte positions into a bit-7..bit-0 view with highlights."""
    lines = []
    for pos in breakout:
        if pos >= len(values) or values[pos] is None:
            continue
        b = values[pos]
        bits = bit_changed_at.get(pos)
        idx_hdr = " ".join(str(k) for k in range(7, -1, -1))
        val_cells, mark_cells = [], []
        for k in range(7, -1, -1):
            bitval = str((b >> k) & 1)
            age = now - (bits[k] if bits else float("-inf"))
            if use_color:
                if age < hl * 0.5:
                    val_cells.append(f"{CHANGED}{bitval}{RESET}")
                elif age < hl:
                    val_cells.append(f"{CHANGED_FADE}{bitval}{RESET}")
                else:
                    val_cells.append(bitval)
            else:
                val_cells.append(bitval)
                mark_cells.append("^" if age < hl else " ")
        lines.append(f"byte {pos} = 0x{b:02X} = {b:08b}b")
        lines.append((f"{DIM}bit {idx_hdr}{RESET}") if use_color
                     else f"bit {idx_hdr}")
        lines.append("    " + " ".join(val_cells))
        if not use_color:
            lines.append("    " + " ".join(mark_cells))
        lines.append("")
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def build_status(args, count, start_wall, framing, watch, log_path, logged):
    elapsed = int(time.time() - start_wall)
    mm, ss = divmod(elapsed, 60)
    s = (f"{args.device} {args.channel} @ {args.baudrate} baud"
         f"    {framing}"
         f"    packets: {count}"
         f"    elapsed: {mm:02d}:{ss:02d}"
         f"    highlight: {args.highlight_seconds:g}s")
    if watch:
        s += "    watch: [" + ",".join(str(w) for w in watch) + "]"
        if log_path:
            s += f" -> {log_path} ({logged})"
    return s


# ---- demo source ------------------------------------------------------------
def demo_bytes(header_bytes):
    """Synthetic stream: a mostly-constant packet with occasional changes."""
    import random
    base = [0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x00]
    while True:
        payload = list(base)
        if random.random() < 0.6:
            payload[random.randrange(len(payload) - 1)] = random.randrange(256)
        payload[-1] = sum(payload[:-1]) & 0xFF          # trailing checksum
        for b in header_bytes:
            yield b
        for b in payload:
            yield b
        time.sleep(0.4)


# ---- main loop --------------------------------------------------------------
def run(byte_iter, header_bytes, args, use_color, breakout, watch, log_path):
    hl = args.highlight_seconds
    columns = max(1, args.columns)
    dashboard = sys.stdout.isatty()
    watch_set = frozenset(watch)

    # Choose framing mode.
    if args.length and args.length > 0:
        pkt_iter = packetize_fixed(byte_iter, args.length, max(0, args.offset))
        hlen = 0
        framing = f"fixed {args.length}B (offset {max(0, args.offset)})"
    else:
        pkt_iter = packetize_header(byte_iter, header_bytes)
        hlen = len(header_bytes)
        framing = f"header 0x{args.header.upper()}"

    # Open change log if requested.
    log_fh = None
    if watch and log_path:
        try:
            log_fh = open(log_path, "a", buffering=1)
            log_fh.write(f"# uart_watch log opened {datetime.now().isoformat()}"
                         f"  framing={framing}  watch={list(watch)}\n")
        except OSError as e:
            sys.stderr.write(f"Could not open log file {log_path!r}: {e}\n")
            log_fh = None

    values, changed_at = [], []
    bit_changed_at = {p: [float("-inf")] * 8 for p in breakout}
    first = True
    count = 0
    logged = 0
    last_paint = 0.0
    start_wall = time.time()

    if dashboard:
        sys.stdout.write(HIDE_CURSOR + CLEAR_HOME)
        sys.stdout.flush()

    try:
        for pkt in pkt_iter:
            count += 1
            now = time.monotonic()
            n = len(pkt)

            while len(values) < n:
                values.append(None)
                changed_at.append(float("-inf"))
            del values[n:]
            del changed_at[n:]

            changed = False
            for i in range(n):
                old, new = values[i], pkt[i]
                if old != new:
                    if first:
                        changed_at[i] = float("-inf")
                    else:
                        changed_at[i] = now
                        changed = True
                        if i in bit_changed_at and old is not None:
                            xor = old ^ new
                            for k in range(8):
                                if (xor >> k) & 1:
                                    bit_changed_at[i][k] = now
                        # Log flagged-byte changes.
                        if log_fh is not None and i in watch_set \
                                and old is not None:
                            logged += 1
                            ts = datetime.now().isoformat(timespec="milliseconds")
                            log_fh.write(
                                f"{ts}  pkt {count}  byte {i}: "
                                f"0x{old:02X} -> 0x{new:02X}  "
                                f"(dec {old} -> {new})  "
                                f"(bin {old:08b} -> {new:08b})\n")
                    values[i] = new
            first = False

            if changed or (now - last_paint) >= PAINT_INTERVAL:
                lines = [build_status(args, count, start_wall, framing,
                                      watch, log_path if log_fh else "", logged),
                         ""]
                lines += render_grid(values, changed_at, hlen, now, hl,
                                     use_color, columns, watch_set)
                if breakout:
                    bo = render_breakouts(values, bit_changed_at, breakout,
                                          now, hl, use_color)
                    if bo:
                        lines += ["", "── bit breakout ──", ""] + bo
                if dashboard:
                    sys.stdout.write(CURSOR_HOME + "\n".join(lines) +
                                     "\n" + CLEAR_BELOW)
                    sys.stdout.flush()
                elif changed or count == 1:
                    print("\n".join(lines) + "\n", flush=True)
                last_paint = now
    finally:
        if log_fh is not None:
            log_fh.close()

    return count


def main():
    args = parse_args()
    use_color = sys.stdout.isatty() and not args.no_color
    breakout = parse_int_list(args.breakout)
    watch = parse_int_list(args.watch)
    log_path = args.log or ("uart_changes.log" if watch else "")

    try:
        header_bytes = bytes.fromhex(args.header)
    except ValueError:
        sys.exit(f"Error: --header must be hex (got {args.header!r})")

    if args.demo:
        try:
            run(demo_bytes(header_bytes), header_bytes, args, use_color,
                breakout, watch, log_path)
        except KeyboardInterrupt:
            pass
        finally:
            if sys.stdout.isatty():
                sys.stdout.write(SHOW_CURSOR + "\n")
                sys.stdout.flush()
        return

    if shutil.which("sigrok-cli") is None:
        sys.exit("Error: sigrok-cli not found. Install sigrok "
                 "(e.g. 'sudo apt install sigrok-cli', or from "
                 "https://sigrok.org) and ensure fx2lafw firmware is present.")

    cmd = build_command(args)
    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                            text=True, bufsize=1)
    count = 0
    try:
        count = run(iter_bytes_from_sigrok(proc), header_bytes, args,
                    use_color, breakout, watch, log_path)
    except KeyboardInterrupt:
        pass
    finally:
        if sys.stdout.isatty():
            sys.stdout.write(SHOW_CURSOR + "\n")
            sys.stdout.flush()
        proc.terminate()
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired:
            proc.kill()
        if count == 0 and proc.stderr is not None:
            err = proc.stderr.read()
            if err.strip():
                sys.stderr.write("\nsigrok-cli said:\n" + err)


if __name__ == "__main__":
    main()
